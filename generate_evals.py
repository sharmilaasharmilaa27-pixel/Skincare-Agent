def generate_evals():
    cases = []
    for q, source in DOCS_QUESTIONS:
        cases.append({"question": q, "category": "in-docs", "source": source})
    for q in INJECTION_CASES:
        cases.append({"question": q, "category": "injection"})
    for q in UNRESOLVABLE_CASES:
        cases.append({"question": q, "category": "unresolvable"})
    for q in CHAIN_CASES:
        cases.append({"question": q, "category": "chain"})

    random.shuffle(cases)

    with open(EVAL_PATH, "w") as f:
        for case in cases:
            f.write(json.dumps(case) + "\n")

    print(f"Generated {len(cases)} eval cases")
    print(f"  in-docs: {sum(1 for c in cases if c['category']=='in-docs')}")
    print(f"  injection: {sum(1 for c in cases if c['category']=='injection')}")
    print(f"  unresolvable: {sum(1 for c in cases if c['category']=='unresolvable')}")
    print(f"  chain: {sum(1 for c in cases if c['category']=='chain')}")

    return cases

if __name__ == "__main__":
    generate_evals()
